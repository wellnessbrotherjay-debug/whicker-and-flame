import pg from 'pg';

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL DEFAULT '',
  passwordhash text NOT NULL,
  preferences jsonb NOT NULL DEFAULT '{}',
  createddate timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
  tokenhash text PRIMARY KEY,
  fkuserid bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expiresdate timestamptz NOT NULL,
  createddate timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_sessions_fkuserid ON sessions(fkuserid);
CREATE TABLE IF NOT EXISTS favorites (
  fkuserid bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipeid text NOT NULL,
  createddate timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (fkuserid, recipeid)
);
CREATE TABLE IF NOT EXISTS planentries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fkuserid bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plandate date NOT NULL,
  mealslot text NOT NULL CHECK (mealslot IN ('breakfast', 'lunch', 'dinner')),
  recipeid text NOT NULL,
  servings integer NOT NULL CHECK (servings BETWEEN 1 AND 20),
  createddate timestamptz NOT NULL DEFAULT now(),
  UNIQUE (fkuserid, plandate, mealslot, recipeid)
);
CREATE TABLE IF NOT EXISTS listrecipes (
  fkuserid bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipeid text NOT NULL,
  servings integer NOT NULL CHECK (servings BETWEEN 1 AND 20),
  createddate timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (fkuserid, recipeid)
);
CREATE TABLE IF NOT EXISTS shoppingmarks (
  fkuserid bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  itemkey text NOT NULL,
  state text NOT NULL CHECK (state IN ('checked', 'removed')),
  PRIMARY KEY (fkuserid, itemkey)
);
CREATE TABLE IF NOT EXISTS posts (
  id uuid PRIMARY KEY,
  title text NOT NULL,
  status text NOT NULL CHECK (status IN ('idea', 'script', 'production', 'review', 'approved', 'scheduled', 'published')),
  pillar text NOT NULL,
  format text NOT NULL,
  platforms text[] NOT NULL,
  characters text[] NOT NULL DEFAULT '{}',
  recipeid text,
  episode integer,
  hook text NOT NULL DEFAULT '',
  script text NOT NULL DEFAULT '',
  shotlist text NOT NULL DEFAULT '',
  captions jsonb NOT NULL DEFAULT '{}',
  hashtags text NOT NULL DEFAULT '',
  poll text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  reviewnote text NOT NULL DEFAULT '',
  mediaurl text,
  plandate date,
  plantime text,
  scheduledfor timestamptz,
  slug text NOT NULL UNIQUE,
  published jsonb NOT NULL DEFAULT '{}',
  metrics jsonb NOT NULL DEFAULT '{}',
  createddate timestamptz NOT NULL DEFAULT now(),
  modifieddate timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_posts_plandate ON posts(plandate);
CREATE TABLE IF NOT EXISTS brandkit (
  id integer PRIMARY KEY CHECK (id = 1),
  content jsonb NOT NULL,
  modifieddate timestamptz NOT NULL DEFAULT now()
);
-- Counts only: how often a post's link was opened and what followed. No person is recorded.
CREATE TABLE IF NOT EXISTS linkcounts (
  slug text NOT NULL,
  event text NOT NULL CHECK (event IN ('open', 'save', 'plan', 'list', 'cooked')),
  day date NOT NULL DEFAULT current_date,
  count integer NOT NULL DEFAULT 0,
  PRIMARY KEY (slug, event, day)
);
CREATE TABLE IF NOT EXISTS jobs (
  id uuid PRIMARY KEY,
  recipeid text NOT NULL,
  prompt text NOT NULL,
  status text NOT NULL,
  videourl text,
  requestid text,
  error text,
  fkpostid uuid REFERENCES posts(id) ON DELETE SET NULL,
  createddate timestamptz NOT NULL DEFAULT now()
);
`;

export async function openDatabase(connectionString) {
  if (!connectionString) throw Error('DATABASE_URL is not set.');
  const pool = new pg.Pool({connectionString, max: 10});
  await pool.query(SCHEMA);
  return pool;
}

export async function transaction(pool, work) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await work(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
