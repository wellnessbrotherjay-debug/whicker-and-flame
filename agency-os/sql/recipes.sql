-- Recipe library: the one place Whisker & Heat meals are built. The website and the phone app read
-- published recipes from here through the Agency OS API; the dashboard's Recipe builder writes them.
CREATE TABLE IF NOT EXISTS agencyos.recipes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fktenantid bigint NOT NULL REFERENCES agencyos.tenants(id),
  slug character varying NOT NULL,
  title character varying NOT NULL,
  status character varying NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  sortorder integer NOT NULL DEFAULT 0,
  recipe jsonb NOT NULL,
  createddate timestamptz NOT NULL DEFAULT now(),
  modifieddate timestamptz NOT NULL DEFAULT now(),
  UNIQUE (fktenantid, slug)
);

CREATE OR REPLACE FUNCTION agencyos.listrecipes(tenant_ character varying, publishedonly_ boolean)
 RETURNS TABLE(answer_ character varying, statuscode_ character varying, statusmsg_ character varying)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'agencyos', 'pg_temp'
AS $function$
DECLARE _functionname character varying = 'agencyos.listrecipes';
BEGIN
  BEGIN
    -- Version: 1.0
    -- Date: 16/10/2026
    -- Purpose: the recipe library. publishedonly_ = true is what the website and phone app read.
    SELECT COALESCE(jsonb_agg(r.recipe || jsonb_build_object('id', r.slug, 'title', r.title, 'status', r.status,
             'sortOrder', r.sortorder, 'modified', r.modifieddate) ORDER BY r.sortorder, r.title), '[]'::jsonb)::character varying
      INTO answer_
      FROM agencyos.recipes r JOIN agencyos.tenants t ON t.id = r.fktenantid
     WHERE t.slug = tenant_ AND r.status <> 'archived' AND (NOT publishedonly_ OR r.status = 'published');
    statuscode_ := 'OK'; statusmsg_ := _functionname || ': success';
    RETURN NEXT;
  EXCEPTION WHEN OTHERS THEN
    answer_ := NULL; statuscode_ := SQLSTATE; statusmsg_ := _functionname || ': ' || SQLERRM;
    RETURN NEXT;
  END;
END;
$function$;

CREATE OR REPLACE FUNCTION agencyos.saverecipe(tenant_ character varying, recipe_ character varying)
 RETURNS TABLE(answer_ character varying, statuscode_ character varying, statusmsg_ character varying)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'agencyos', 'pg_temp'
AS $function$
DECLARE _functionname character varying = 'agencyos.saverecipe';
DECLARE _r jsonb;
DECLARE _tenant bigint;
DECLARE _slug character varying;
DECLARE _title character varying;
DECLARE _status character varying;
BEGIN
  BEGIN
    -- Version: 1.0
    -- Date: 16/10/2026
    -- Purpose: creates or updates one recipe from the Recipe builder. The slug is the recipe's web address and stays fixed.
    _r := recipe_::jsonb;
    SELECT id INTO _tenant FROM agencyos.tenants WHERE slug = tenant_ AND status = 'active';
    IF _tenant IS NULL THEN RAISE EXCEPTION 'unknown tenant %', tenant_ USING ERRCODE = 'P0002'; END IF;
    _title := btrim(COALESCE(_r->>'title', ''));
    IF _title = '' THEN RAISE EXCEPTION 'Give the recipe a title.' USING ERRCODE = '22023'; END IF;
    _slug := COALESCE(NULLIF(btrim(_r->>'id'), ''), btrim(regexp_replace(lower(_title), '[^a-z0-9]+', '-', 'g'), '-'));
    IF _slug !~ '^[a-z0-9]+(-[a-z0-9]+)*$' THEN RAISE EXCEPTION 'The recipe address may use only lowercase letters, numbers and dashes.' USING ERRCODE = '22023'; END IF;
    IF jsonb_typeof(_r->'ingredients') <> 'array' OR jsonb_array_length(_r->'ingredients') = 0 THEN RAISE EXCEPTION 'Add at least one ingredient.' USING ERRCODE = '22023'; END IF;
    IF jsonb_typeof(_r->'steps') <> 'array' OR jsonb_array_length(_r->'steps') = 0 THEN RAISE EXCEPTION 'Add at least one step.' USING ERRCODE = '22023'; END IF;
    IF COALESCE((_r->>'servings')::int, 0) NOT BETWEEN 1 AND 20 THEN RAISE EXCEPTION 'Servings must be 1 to 20.' USING ERRCODE = '22023'; END IF;
    _status := COALESCE(_r->>'status', 'draft');
    INSERT INTO agencyos.recipes(fktenantid, slug, title, status, sortorder, recipe)
    VALUES (_tenant, _slug, _title, _status, COALESCE((_r->>'sortOrder')::int, 0), _r - 'id' - 'title' - 'status' - 'sortOrder' - 'modified')
    ON CONFLICT (fktenantid, slug) DO UPDATE SET title = EXCLUDED.title, status = EXCLUDED.status, sortorder = EXCLUDED.sortorder,
      recipe = EXCLUDED.recipe, modifieddate = now();
    answer_ := jsonb_build_object('id', _slug, 'status', _status)::character varying;
    statuscode_ := 'OK'; statusmsg_ := _functionname || ': success';
    RETURN NEXT;
  EXCEPTION WHEN OTHERS THEN
    answer_ := NULL; statuscode_ := SQLSTATE; statusmsg_ := _functionname || ': ' || SQLERRM;
    RETURN NEXT;
  END;
END;
$function$;

REVOKE ALL ON FUNCTION agencyos.listrecipes(character varying, boolean), agencyos.saverecipe(character varying, character varying) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION agencyos.listrecipes(character varying, boolean), agencyos.saverecipe(character varying, character varying) TO architect, service_user;
